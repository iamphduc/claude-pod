// Writes src/agentprism-openaflow.css: AgentPrism's --agentprism-* tokens
// (OKLCH "L C H" triplets) computed from Open AFlow's hex tokens in
// ../../shared/tokens.css, for light, dark, and the data-theme overrides.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../../../shared/tokens.css", import.meta.url), "utf8");
const block = (re) => Object.fromEntries([...css.match(re)[1].matchAll(/--([\w-]+):\s*(#[0-9a-f]{6})/gi)].map((m) => [m[1], m[2]]));
const light = block(/:root \{([\s\S]*?)\n\}/);
const dark = block(/:root\[data-theme="dark"\] \{([\s\S]*?)\n\}/);

const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
function oklch(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => lin(parseInt(hex.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const C = Math.hypot(A, B);
  const H = C < 0.0001 ? 0 : ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360;
  return `${(L * 100).toFixed(2)}% ${C.toFixed(4)} ${H.toFixed(2)}`;
}

// AgentPrism token -> Open AFlow token. Status colours only feed dots; every
// category (agent/tool/llm...) badge and avatar is neutral grey, as Open AFlow
// keeps colour for status only.
const categories = ["llm", "agent", "tool", "chain", "retrieval", "embedding", "guardrail", "create-agent", "span", "event", "unknown"];
const map = {
  background: "bg", foreground: "fg", primary: "primary-bg", "primary-foreground": "primary-fg",
  secondary: "hover", "secondary-foreground": "muted", muted: "hover", "muted-foreground": "muted",
  accent: "hover", "accent-foreground": "fg", brand: "fg", "brand-foreground": "bg",
  "brand-secondary": "fg", "brand-secondary-foreground": "bg",
  border: "border", "border-subtle": "border", "border-strong": "border-strong", "border-inverse": "fg",
  success: "ready", "success-muted": "hover", "success-muted-foreground": "fg",
  error: "blocked", "error-muted": "hover", "error-muted-foreground": "fg",
  warning: "needs-you", "warning-muted": "hover", "warning-muted-foreground": "fg",
  pending: "running", "pending-muted": "hover", "pending-muted-foreground": "fg",
  "code-string": "fg", "code-number": "fg", "code-key": "muted", "code-base": "muted",
  "badge-default": "hover", "badge-default-foreground": "muted",
  "badge-claude-thinking": "hover", "badge-claude-thinking-foreground": "muted",
  "context-source-conversation": "muted",
};
for (const c of categories) {
  map[`avatar-${c}`] = "muted";
  map[`badge-${c}`] = "hover";
  map[`badge-${c}-foreground`] = "muted";
  map[`timeline-${c}`] = c === "tool" ? "faint" : "muted";
}
const vars = (t) => Object.entries(map).map(([k, v]) => `  --agentprism-${k}: ${oklch(t[v])};`).join("\n");
const darkVars = vars(dark).replace(/^/gm, "  ");

writeFileSync(new URL("../src/agentprism-openaflow.css", import.meta.url),
`/* Generated by scripts/gen-theme.mjs from ../../shared/tokens.css. Do not edit. */
:root {
${vars(light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkVars}
  }
}

:root[data-theme="dark"] {
${vars(dark)}
}
`);
console.log("wrote", Object.keys(map).length, "tokens");
